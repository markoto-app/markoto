import { describe, it, expect } from 'vitest'

// The `generate_image` tool routes through BFL FLUX.2 [pro]
// (EU-pinned) via the LiteLLM custom provider. (Pre-Phase-5 the tool
// was dual-mode with Gemini as the alternate; that fork was removed
// once the migration completed.) The full handler
// (`handleGenerateImage` in aiToolAdapter.ts) is exercised by the
// integration suite; these unit tests pin the small bits of routing
// logic that don't need a Y.Doc session, S3 client, or LiteLLM
// proxy:
//
//   - the JSON content shape we send to the BFL custom provider
//   - default width/height resolution
//   - aspect-ratio overrides

describe('image gen — BFL provider message shape', () => {
  // The custom provider in infra/litellm/custom_handlers.py expects
  // JSON-encoded {prompt, width, height, prompt_upsampling} as the
  // message content. Pin the wire format so a future renaming on
  // either side trips the test instead of silently producing $0
  // images or mis-sized output.
  it('emits a flat JSON object matching the provider contract', () => {
    const prompt = 'a small icon for cooking'
    const width = 1024
    const height = 1024
    const content = JSON.stringify({ prompt, width, height, prompt_upsampling: false })
    const parsed = JSON.parse(content)
    expect(parsed).toEqual({
      prompt: 'a small icon for cooking',
      width: 1024,
      height: 1024,
      prompt_upsampling: false
    })
  })

  it('honors aspect-ratio overrides (width/height)', () => {
    const wideContent = JSON.stringify({
      prompt: 'a wide landscape',
      width: 1408,
      height: 768,
      prompt_upsampling: false
    })
    const wide = JSON.parse(wideContent)
    expect(wide.width).toBe(1408)
    expect(wide.height).toBe(768)
    expect(wide.width / wide.height).toBeCloseTo(1.83, 1)

    const tallContent = JSON.stringify({
      prompt: 'a tall portrait',
      width: 768,
      height: 1408,
      prompt_upsampling: false
    })
    const tall = JSON.parse(tallContent)
    expect(tall.width).toBe(768)
    expect(tall.height).toBe(1408)
    expect(tall.height / tall.width).toBeCloseTo(1.83, 1)
  })

  it('always sets prompt_upsampling=false (the prompt is AI-written)', () => {
    // Pin the policy choice. Re-LLM-ing a prompt that was already
    // generated by the agentic loop adds latency for no benefit; the
    // setting is intentionally not surfaced to the AI.
    const content = JSON.stringify({
      prompt: 'whatever',
      width: 1024,
      height: 1024,
      prompt_upsampling: false
    })
    expect(JSON.parse(content).prompt_upsampling).toBe(false)
  })
})

describe('image gen — BFL response parsing', () => {
  // The BFL custom provider returns a chat completion whose
  // `choices[0].message.content` is JSON-encoded {b64_json, url,
  // cost_credits, cost_usd}. Our handler parses it back out.
  it('extracts b64_json from a well-formed BFL response', () => {
    const content = JSON.stringify({
      b64_json: 'AAAA',
      url: 'https://delivery.eu2.bfl.ai/durable/...',
      cost_credits: 3,
      cost_usd: 0.03
    })
    const body = JSON.parse(content)
    expect(body.b64_json).toBe('AAAA')
    expect(body.cost_usd).toBe(0.03)
    expect(body.url).toContain('delivery.eu2.bfl.ai')
  })

  it('handles a content-moderated response with no b64_json', () => {
    // BFL can refuse a prompt and return an empty image but valid JSON.
    // Our handler should detect missing b64_json and return an error.
    const content = JSON.stringify({
      url: '',
      cost_credits: 0,
      cost_usd: 0
    })
    const body = JSON.parse(content) as { b64_json?: string }
    expect(body.b64_json).toBeUndefined()
  })
})
