-- Hand-written backfill (not generated by drizzle): anonymous-document
-- retention drops from 180 to 30 days of inactivity in this release.
-- Every anonymous doc that exists now gets a deletion floor of
-- min(now + 30 days, last_active + 180 days): it is never deleted
-- earlier than under the old 180-day rule would have allowed AND never
-- earlier than 30 days after this deploy. Docs created from here on have
-- no floor (NULL) and follow the 30-day rule directly.
UPDATE "documents"
   SET "sweep_not_before" = LEAST(now() + interval '30 days', "last_active" + interval '180 days')
 WHERE "owner_id" IS NULL
   AND "workspace_id" IS NULL;
