// Generates `.nuxt/types/api-inputs.d.ts`: for every API handler Nitro scanned,
// the request input types it declares through `defineApiHandler` (params,
// query, body), keyed like Nitro's `InternalApi` (route pattern → method).
// Nitro types responses itself but not requests; the typed client
// (app/utils/api/client.ts) reads both.
//
// Nitro scans the handler directories before Nuxt fires `nitro:init`, so the
// list is complete there; on every dev rescan Nitro rewrites its own types and
// fires `types:extend`, where this file is regenerated too.

import { join, relative } from 'node:path'
import { addTypeTemplate, defineNuxtModule, updateTemplates } from '@nuxt/kit'
import type { Nitro } from 'nitropack'

const FILENAME = 'types/api-inputs.d.ts'

interface ScannedHandler {
  route?: string
  method?: string
  handler: string
  middleware?: boolean
}

function renderApiInputs(handlers: readonly ScannedHandler[], typesDir: string, contractFile: string): string {
  const routes = new Map<string, Map<string, string>>()
  for (const h of handlers) {
    if (h.middleware || !h.route) continue
    const file = relative(typesDir, h.handler).replace(/\\/g, '/').replace(/\.[cm]?[jt]s$/, '')
    const methods = routes.get(h.route) ?? new Map<string, string>()
    methods.set((h.method ?? 'default').toLowerCase(), `ApiInputOf<typeof import('${file.startsWith('.') ? file : `./${file}`}').default>`)
    routes.set(h.route, methods)
  }
  const contract = relative(typesDir, contractFile).replace(/\\/g, '/')
  const lines = [...routes.keys()].sort().map((route) => {
    const methods = [...(routes.get(route) ?? new Map<string, string>()).entries()].sort(([a], [b]) => a.localeCompare(b))
    return `    '${route}': {\n${methods.map(([m, t]) => `      '${m}': ${t}`).join('\n')}\n    }`
  })
  return `// Generated by modules/api-contract.ts
import type { ApiInputOf } from '${contract}'
declare module '${contract}' {
  interface ApiInputs {
${lines.join('\n')}
  }
}
export {}
`
}

export default defineNuxtModule({
  meta: { name: 'markoto-api-contract' },
  setup(_options, nuxt) {
    let nitro: Nitro | undefined
    const typesDir = join(nuxt.options.buildDir, 'types')
    addTypeTemplate({
      filename: FILENAME,
      getContents: () => renderApiInputs(nitro?.scannedHandlers ?? [], typesDir, join(nuxt.options.rootDir, 'shared/api/contract'))
    })
    nuxt.hook('nitro:init', (n) => {
      nitro = n
      n.hooks.hook('types:extend', async () => {
        await updateTemplates({ filter: t => t.filename === FILENAME })
      })
    })
  }
})
