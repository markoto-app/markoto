#!/usr/bin/env bun
// Fails when tracked text files contain the em-dash character (U+2014).
// The project never uses it: rewrite the sentence with a comma, a colon,
// parentheses or two sentences. Where the character is the SUBJECT of the code
// (a typography test, a sanitizer table), write it as the escape \u2014
// instead of the literal character.
//   bun scripts/checks/no-em-dash.mjs [--summary] [--json]
import { execFileSync } from 'node:child_process'
import { existsSync, readFileSync } from 'node:fs'
import { join } from 'node:path'

const root = execFileSync('git', ['rev-parse', '--show-toplevel'], { encoding: 'utf8' }).trim()
// Written as an escape so this script stays clean itself.
const PATTERN = /\u2014/g

// One entry per required exemption, with the reason.
const EXCLUDE = [
  /^public\//, // generated and vendored assets
  /^drizzle\//, // generated migrations and snapshots
  /(^|\/)(bun\.lock|bun\.lockb|package-lock\.json|pnpm-lock\.yaml|yarn\.lock|uv\.lock)$/,
  /(^|\/)node_modules\//,
  /(^|\/)(\.nuxt|\.output|test-results)\//,
  /\.(png|jpe?g|gif|webp|ico|svg|woff2?|ttf|otf|pdf|zip|gz|docx|pptx|xlsx|mp4|webm)$/i,
  // Sample documents that pictures are rendered from. Their text is hashed
  // into the committed render manifests and shown in recorded screenshots
  // and tour clips, so changing a character means re-rendering those.
  /^tests\/fixtures\/theme-shots\/(?!README\.md$)/,
  /^tests\/e2e\/fixtures\/content\//,
  /^tests\/e2e\/fixtures\/import-files\//,
  /^tests\/e2e\/tour\/content\//,
  /^tests\/e2e\/output\// // generated by a flow run, untracked
]

const files = execFileSync('git', ['ls-files', '-z', '--cached', '--others', '--exclude-standard'], {
  cwd: root,
  encoding: 'utf8',
  maxBuffer: 1 << 28
})
  .split('\0')
  .filter(f => f && !EXCLUDE.some(re => re.test(f)) && existsSync(join(root, f)))

const hits = []
for (const f of files) {
  const text = readFileSync(join(root, f), 'utf8')
  if (text.includes('\0')) continue
  text.split('\n').forEach((line, i) => {
    const n = [...line.matchAll(PATTERN)].length
    if (n) hits.push({ file: f, line: i + 1, count: n })
  })
}

const byFile = new Map()
for (const h of hits) byFile.set(h.file, (byFile.get(h.file) ?? 0) + h.count)
const total = hits.reduce((a, h) => a + h.count, 0)

if (process.argv.includes('--json')) console.log(JSON.stringify(hits, null, 2))
else {
  if (process.argv.includes('--summary')) {
    const byDir = new Map()
    for (const [f, n] of byFile) {
      const d = f.includes('/') ? f.split('/')[0] : '(root)'
      byDir.set(d, (byDir.get(d) ?? 0) + n)
    }
    console.log('by top-level directory:')
    for (const [d, n] of [...byDir].sort((a, b) => b[1] - a[1])) console.log(`  ${String(n).padStart(5)}  ${d}`)
  } else for (const h of hits) console.log(`${h.file}:${h.line}: em-dash`)
  console.log(`\n${total} em-dash character(s) in ${byFile.size} file(s)`)
}
process.exit(hits.length ? 1 : 0)
