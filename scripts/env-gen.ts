#!/usr/bin/env bun
// Generates the files derived from the environment registry (shared/env/):
//
//   .env.example                      dev / hosted template (scripts/setup-env.sh fills its empty secrets)
//   docs/reference/configuration.md   the configuration reference
//   docs/reference/configuration.json machine-readable: every variable with its services, aliases, scope
//   renderer/src/env.generated.ts     the renderer's loader (its image is built from renderer/ alone)
//
//   bun scripts/env-gen.ts           write them
//   bun scripts/env-gen.ts --check   exit 1 when one is out of date (CI)

import { readFileSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'
import { NAMESPACES, RULES, registeredVars, type RegisteredVar } from '../shared/env/registry'
import { nameFor, type AnyVar, type Service } from '../shared/env/define'

const ROOT = resolve(import.meta.dirname, '..')
const GENERATED_NOTE = 'GENERATED by `bun scripts/env-gen.ts` from the registry in shared/env/ — edit the registry, not this file.'

function shown(value: unknown): string {
  if (value === undefined) return ''
  if (Array.isArray(value)) return value.join(',')
  return String(value)
}

function requiredText(spec: AnyVar): string {
  if (!spec.required) return ''
  if (spec.required === 'always') return 'always'
  if (spec.required === 'production') return 'in production'
  return `when ${spec.required.when}`
}

/** Paid-plan tier / price overrides are documented once, not as 100 lines (the JSON lists each). */
function isBulkTier(namespace: string, spec: AnyVar): boolean {
  return namespace === 'tiers' && !spec.name.startsWith('TIER_FREE_')
}

const BULK_TIER_NOTE = 'TIER_PRO_* / TIER_TEAM_* / TIER_BUSINESS_* take the same fields; TIER_<PLAN>_PRICE_<EUR|CHF>[_YEAR] the planned prices.'

// ─── .env.example ──────────────────────────────────────────────────────────

export function envExample(): string {
  const out: string[] = [
    '# markoto — environment template (development + hosted deploys).',
    `# ${GENERATED_NOTE}`,
    '#',
    '# Self-hosting? Don\'t copy this file: run ./install.sh, which writes a',
    '# complete .env for docker-compose.selfhost.yml (docs/SELF-HOSTING.md).',
    '#',
    '# Daily dev: `docker compose -f docker-compose.dev.yml up -d` (infra only) +',
    '# `bun run dev` on the host; the values below match docker-compose.dev.yml.',
    '# `make setup` copies this file to .env and generates every empty secret.',
    '#',
    '# Uncommented lines are the ones a dev stack needs; commented ones show the',
    '# default. Every variable is described in docs/reference/configuration.md;',
    '# the app, sync server and renderer validate their set at boot.',
    ''
  ]
  for (const ns of Object.values(NAMESPACES)) {
    const vars = (Object.values(ns.vars) as AnyVar[]).filter(spec => spec.scope !== 'test' && !spec.internal)
    if (vars.length === 0) continue
    out.push(`# ─── ${ns.title} ${'─'.repeat(Math.max(3, 72 - ns.title.length))}`)
    out.push(`# ${ns.intro}`)
    for (const spec of vars) {
      if (isBulkTier(ns.name, spec)) continue
      out.push(`# ${spec.doc}`)
      if (spec.example !== undefined) out.push(`${spec.name}=${spec.example}`)
      else out.push(`# ${spec.name}=${spec.secret ? '' : shown(spec.default)}`)
    }
    if (ns.name === 'tiers') out.push(`# ${BULK_TIER_NOTE}`)
    out.push('')
  }
  return `${out.join('\n').trimEnd()}\n`
}

// ─── docs/reference/configuration.md ───────────────────────────────────────

const SERVICE_LABEL: Record<Service, string> = {
  app: 'app', sync: 'sync', renderer: 'renderer', litellm: 'litellm', markitdown: 'markitdown', backup: 'backup', compose: 'compose', build: 'build'
}

function cell(text: string): string {
  return text.replace(/\|/g, '\\|').replace(/\n/g, ' ')
}

function servicesCell(spec: AnyVar): string {
  return spec.services.map((s) => {
    const alias = spec.aliases?.[s]
    return alias ? `${SERVICE_LABEL[s]} (as \`${alias}\`)` : SERVICE_LABEL[s]
  }).join(', ')
}

function defaultCell(spec: AnyVar): string {
  if (spec.defaultDoc) return spec.defaultDoc
  if (spec.secret) return ''
  const d = shown(spec.default)
  return d === '' ? (spec.default === undefined ? '' : '(empty)') : `\`${d}\``
}

export function configurationReference(): string {
  const out: string[] = [
    '# Configuration reference',
    '',
    `<!-- ${GENERATED_NOTE} -->`,
    '',
    'Every environment variable markoto reads or passes, grouped by area. The app, the sync server and the renderer validate their set at boot and refuse to start with a list of every problem (wrong type, missing required value, inconsistent combination). How to add a variable: [docs/contributing/configuration.md](../contributing/configuration.md).',
    '',
    '- **Services** — which process reads it (`compose` = only the compose files / install.sh interpolate it). Some containers read the same value under another name, shown in brackets.',
    '- **Scope** — `both` = self-hosted and hosted, `self-host`, `hosted`, `dev`, `test`.',
    '- **Booleans** accept `true`/`false`, `1`/`0`, `yes`/`no`, `on`/`off`. An empty value means unset (the default applies), except where noted.',
    ''
  ]
  for (const ns of Object.values(NAMESPACES)) {
    out.push(`## ${ns.title}`, '', ns.intro, '')
    out.push('| Variable | Type | Default | Required | Services | Scope | Description |')
    out.push('|---|---|---|---|---|---|---|')
    for (const spec of Object.values(ns.vars) as AnyVar[]) {
      if (isBulkTier(ns.name, spec)) continue
      const notes = [spec.doc]
      if (spec.emptyIsValue) notes.push('Set but empty is a value of its own.')
      if (spec.secret) notes.push('Secret.')
      if (spec.deprecatedNames?.length) notes.push(`Formerly ${spec.deprecatedNames.map(n => `\`${n}\``).join(', ')}.`)
      if (spec.notPassed) notes.push(`Not passed by the compose files: ${spec.notPassed}.`)
      out.push(`| \`${spec.name}\` | ${cell(spec.type.label)} | ${cell(defaultCell(spec))} | ${requiredText(spec)} | ${servicesCell(spec)} | ${spec.scope} | ${cell(notes.join(' '))} |`)
    }
    if (ns.name === 'tiers') out.push('', `${BULK_TIER_NOTE} Each is listed in [configuration.json](configuration.json).`)
    out.push('')
  }
  out.push('## Cross-field rules', '', 'Checked at boot after every value parsed. Rules marked *warning* only log; *relaxed* ones are skipped in test mode.', '')
  out.push('| Rule | Variables | |', '|---|---|---|')
  for (const rule of RULES) {
    const flags = [rule.warning ? 'warning' : '', rule.relaxedInTestMode ? 'relaxed' : ''].filter(Boolean).join(', ')
    out.push(`| ${cell(rule.doc)} | ${rule.vars.map(v => `\`${v}\``).join(', ')} | ${flags} |`)
  }
  return `${out.join('\n').trimEnd()}\n`
}

// ─── docs/reference/configuration.json ─────────────────────────────────────

export function configurationJson(): string {
  const vars = registeredVars().map(({ namespace, key, spec }) => ({
    name: spec.name,
    namespace,
    key,
    type: spec.type.label,
    services: spec.services,
    names: Object.fromEntries(spec.services.map(s => [s, nameFor(spec, s)])),
    scope: spec.scope,
    required: requiredText(spec) || null,
    secret: spec.secret === true,
    default: spec.secret ? null : (spec.default ?? null),
    passedByCompose: spec.notPassed === undefined,
    deprecatedNames: spec.deprecatedNames ?? []
  }))
  return `${JSON.stringify({ note: GENERATED_NOTE, vars }, null, 2)}\n`
}

// ─── renderer/src/env.generated.ts ─────────────────────────────────────────

export function rendererEnvModule(): string {
  const coerce = readFileSync(resolve(ROOT, 'shared/env/coerce.ts'), 'utf8')
  const vars = registeredVars().filter(v => v.spec.services.includes('renderer'))
  const groups = new Map<string, RegisteredVar[]>()
  for (const v of vars) groups.set(v.namespace, [...(groups.get(v.namespace) ?? []), v])
  const iface = [...groups].map(([ns, list]) => `  readonly ${ns}: {\n${list.map(({ key, spec }) => {
    const optional = spec.default === undefined && spec.required !== 'always'
    return `    readonly ${key}: ${spec.type.tsType}${optional ? ' | undefined' : ''}`
  }).join('\n')}\n  }`).join('\n')
  const specs = vars.map(({ namespace, key, spec }) => {
    const fields = [
      `group: ${JSON.stringify(namespace)}`,
      `key: ${JSON.stringify(key)}`,
      `name: ${JSON.stringify(nameFor(spec, 'renderer'))}`,
      `type: ${spec.type.expr}`
    ]
    if (spec.default !== undefined) fields.push(`default: ${JSON.stringify(spec.default)}`)
    if (spec.required === 'always' || spec.required === 'production') fields.push(`required: ${JSON.stringify(spec.required)}`)
    if (spec.emptyIsValue) fields.push('emptyIsValue: true')
    return `  { ${fields.join(', ')} }`
  }).join(',\n')
  return `// ${GENERATED_NOTE}
//
// The renderer image is built from renderer/ alone, so it cannot import
// shared/env. This file carries a copy of shared/env/coerce.ts (exports
// dropped: only the loader below is the module's API) and
// the renderer's slice of the registry; tests/unit/env/generated.test.ts
// checks that it parses exactly like loadEnv('renderer').

/* eslint-disable */
${coerce.replace(/^\/\/.*\n/gm, '').replace(/^export /gm, '').trim()}

interface Spec {
  group: string
  key: string
  name: string
  type: Coercer<unknown>
  default?: unknown
  required?: 'always' | 'production'
  emptyIsValue?: boolean
}

const SPECS: readonly Spec[] = [
${specs}
]

export interface RendererEnv {
${iface}
}

/** Parse and validate the renderer's environment; throws with every problem listed. */
export function loadRendererEnv(source: Record<string, string | undefined> = process.env): RendererEnv {
  const problems: string[] = []
  const out: Record<string, Record<string, unknown>> = {}
  for (const spec of SPECS) {
    const raw = source[spec.name]?.trim()
    let value: unknown = spec.default
    if (raw === '' && spec.emptyIsValue) {
      value = ''
    } else if (!raw) {
      if (spec.required === 'always' || (spec.required === 'production' && source.NODE_ENV === 'production')) {
        problems.push(\`\${spec.name}: required, not set\`)
      }
    } else {
      try {
        value = spec.type.parse(raw)
      } catch (e) {
        if (!(e instanceof EnvValueError)) throw e
        problems.push(\`\${spec.name}: \${e.message}\`)
      }
    }
    ;(out[spec.group] ??= {})[spec.key] = value
  }
  if (problems.length > 0) {
    throw new Error(\`Invalid configuration of the renderer (\${problems.length === 1 ? '1 problem' : \`\${problems.length} problems\`}):\\n\`
      + problems.map(p => \`  - \${p}\`).join('\\n')
      + '\\nEvery variable is described in docs/reference/configuration.md.')
  }
  // Built field by field from RENDERER_VARS, whose groups and keys are RendererEnv's.
  return out as unknown as RendererEnv
}
`
}

// ─── main ──────────────────────────────────────────────────────────────────

const TARGETS: Array<[string, () => string]> = [
  ['.env.example', envExample],
  ['docs/reference/configuration.md', configurationReference],
  ['docs/reference/configuration.json', configurationJson],
  ['renderer/src/env.generated.ts', rendererEnvModule]
]

if (import.meta.main) {
  const check = process.argv.includes('--check')
  let stale = 0
  for (const [path, render] of TARGETS) {
    const file = resolve(ROOT, path)
    const next = render()
    let current = ''
    try {
      current = readFileSync(file, 'utf8')
    } catch { /* missing = stale */ }
    if (current === next) continue
    if (check) {
      console.error(`env-gen: ${path} is out of date — run \`bun scripts/env-gen.ts\``)
      stale++
    } else {
      writeFileSync(file, next)
      console.log(`env-gen: wrote ${path}`)
    }
  }
  if (stale > 0) process.exit(1)
}
